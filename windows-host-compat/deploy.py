#!/usr/bin/env python3
"""Install the Windows host adapter with a dedicated key and local SSH alias."""
import argparse
import base64
import io
import json
import os
from pathlib import Path
import re
import shutil
import subprocess
import sys
import time
import zipfile

ROOT = Path(__file__).resolve().parent
FILES = ['install.ps1', 'uninstall.ps1', 'launcher.cs', 'manager.py', 'env.sh',
         'bin/login-sh', 'bin/codex', 'bin/pkill', 'bin/awk']


def executable(name):
    # Prefer the same Windows OpenSSH implementation used by Desktop, even if
    # Git's OpenSSH precedes it in PATH. No shell=True / cmd.exe quoting layer.
    if os.name == 'nt' and name in ('ssh', 'ssh-keygen'):
        native = Path(os.environ['WINDIR']) / 'System32/OpenSSH' / (name + '.exe')
        if native.is_file():
            return str(native)
    found = shutil.which(name)
    if not found:
        raise RuntimeError(f'{name} was not found; install it or add it to PATH')
    return found


def powershell(script):
    return ['powershell.exe', '-NoLogo', '-NoProfile', '-NonInteractive',
            '-EncodedCommand', base64.b64encode(script.encode('utf-16le')).decode('ascii')]


def protect_file(path):
    if os.name != 'nt':
        path.chmod(0o600)
        return
    # Set an exact user-only DACL by SID, independent of localized account names.
    encoded = base64.b64encode(str(path).encode('utf-8')).decode('ascii')
    script = r'''
$ErrorActionPreference='Stop'
$path=[Text.Encoding]::UTF8.GetString([Convert]::FromBase64String(''' + "'" + encoded + "'" + r'''))
$sid=[Security.Principal.WindowsIdentity]::GetCurrent().User
$acl=[IO.File]::GetAccessControl($path)
if($acl.GetOwner([Security.Principal.SecurityIdentifier]) -ne $sid){throw 'SSH file is not owned by the current user'}
$acl.SetAccessRuleProtection($true,$false)
foreach($rule in @($acl.Access)){$acl.RemoveAccessRuleSpecific($rule)}
$acl.AddAccessRule([Security.AccessControl.FileSystemAccessRule]::new($sid,'FullControl','Allow'))
[IO.File]::SetAccessControl($path,$acl)
'''
    subprocess.run(powershell(script), check=True, capture_output=True)


def identity_path(key):
    value = key.as_posix()
    if any(c in value for c in '\r\n\0"%$'):
        raise RuntimeError('IdentityFile path contains an unsupported SSH expansion or quote')
    return '"' + value + '"'


def effective(ssh, destination):
    raw = subprocess.check_output([ssh, '-G', destination])
    values = {}
    for line in raw.decode('utf-8-sig').splitlines():
        name, _, value = line.partition(' ')
        values.setdefault(name, value)  # IdentityFile can occur more than once.
    return values


def ensure_key(key):
    key.parent.mkdir(parents=True, exist_ok=True)
    public_path = Path(str(key) + '.pub')
    if key.exists() != public_path.exists():
        raise RuntimeError('Incomplete key pair exists; refusing to overwrite either file')
    if not key.exists():
        # Python's subprocess preserves the empty -N argument on Windows.
        subprocess.run([executable('ssh-keygen'), '-q', '-t', 'ed25519', '-N', '',
                        '-C', 'codex-windows-ssh-compat', '-f', str(key)], check=True)
    public = public_path.read_text(encoding='utf-8-sig').strip()
    if not re.fullmatch(r'ssh-ed25519 [A-Za-z0-9+/=]+ codex-windows-ssh-compat', public):
        raise RuntimeError('Use a dedicated key generated by this installer')
    protect_file(key)
    derived = subprocess.check_output([executable('ssh-keygen'), '-y', '-f', str(key)], timeout=10)
    if derived.decode('ascii').strip().split()[:2] != public.split()[:2]:
        raise RuntimeError('Private/public key mismatch')
    return public + '\n'


def archive_payload(public):
    payload = io.BytesIO()
    with zipfile.ZipFile(payload, 'w', zipfile.ZIP_DEFLATED) as archive:
        for name in FILES:
            # Windows git autocrlf and PowerShell BOMs must never reach Bash.
            archive.writestr(name, (ROOT / name).read_text(encoding='utf-8-sig').replace('\r\n', '\n'))
        archive.writestr('client.pub', public)
    return payload.getvalue()


def alias_block(alias, values, key):
    for name in ('hostname', 'user', 'port'):
        if not values.get(name) or re.search(r'[\s"\x00-\x1f]', values[name]):
            raise RuntimeError('Unsupported effective SSH ' + name)
    # A flattened alias would silently lose jump/proxy configuration.
    if values.get('proxycommand', 'none') != 'none' or values.get('proxyjump', 'none') != 'none':
        raise RuntimeError('ProxyCommand/ProxyJump requires a separately reviewed alias')
    return (f'Host {alias}\n  HostName {values["hostname"]}\n  User {values["user"]}\n'
            f'  Port {values["port"]}\n  IdentityFile {identity_path(key)}\n  IdentitiesOnly yes\n'
            '  BatchMode yes\n  StrictHostKeyChecking yes\n\n')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('destination', help='Existing working user@host or SSH alias')
    parser.add_argument('--alias', default='windows-codex-compat')
    parser.add_argument('--key', type=Path, default=Path.home() / '.ssh/codex_windows_compat_ed25519')
    parser.add_argument('--check', action='store_true', help='Read-only remote inventory; no key or installation changes')
    parser.add_argument('--prepare-key', action='store_true', help='Prepare only the dedicated local key; do not contact the host')
    args = parser.parse_args()
    if not re.fullmatch(r'[a-zA-Z0-9_-]+', args.alias):
        parser.error('Use an alias containing only letters, digits, underscores and hyphens')
    if args.destination.startswith('-') or any(c in args.destination for c in '\r\n\0'):
        parser.error('Invalid SSH destination')
    key = args.key.expanduser().resolve()
    identity_path(key)
    ssh = executable('ssh')
    if args.prepare_key:
        ensure_key(key)
        print('Dedicated local key prepared; no remote or SSH config changes')
        return
    config = Path.home() / '.ssh/config'
    original_bytes = config.read_bytes() if config.exists() else b''
    original = original_bytes.decode('utf-8-sig')
    if original_bytes.startswith(b'\xef\xbb\xbf'):
        raise RuntimeError('Existing SSH config has a UTF-8 BOM; save it as UTF-8 without BOM before deployment')
    values = effective(ssh, args.destination)
    block = alias_block(args.alias, values, key)
    alias_values = effective(ssh, args.alias)
    declared = any(args.alias.lower() in line.split()[1:] for line in original.lower().splitlines()
                   if line.strip().startswith('host '))
    exists = declared or alias_values.get('hostname', args.alias).lower() != args.alias.lower()
    if exists and not args.check:
        expected = (values['hostname'], values['user'], values['port'], str(key).replace('\\', '/'))
        actual = tuple(alias_values.get(k, '') for k in ('hostname', 'user', 'port')) + (
            alias_values.get('identityfile', '').strip('"').replace('\\', '/'),)
        if actual != expected:
            raise RuntimeError('SSH alias already resolves differently; preserved. Select another --alias and --key')
        if (alias_values.get('identitiesonly') != 'yes' or alias_values.get('batchmode') != 'yes'
                or alias_values.get('stricthostkeychecking') not in ('yes', 'true')):
            raise RuntimeError('Existing alias has different authentication/host-key options; preserved')
    ssh_args = [ssh, '-T', '-o', 'BatchMode=yes', '-o', 'StrictHostKeyChecking=yes',
                '-o', 'ConnectTimeout=10', args.destination]
    inventory = r'''
$ErrorActionPreference='Stop';[Console]::OutputEncoding=[Text.UTF8Encoding]::new($false)
$root=Join-Path $env:LOCALAPPDATA 'CodexSshCompat'
$python=Get-Command python.exe -CommandType Application -ErrorAction SilentlyContinue | Select-Object -First 1
$cli=Get-ChildItem (Join-Path $env:LOCALAPPDATA 'OpenAI\Codex\bin') -Filter codex.exe -Recurse -ErrorAction SilentlyContinue | Sort-Object LastWriteTimeUtc -Descending | Select-Object -First 1
$state=Join-Path $root 'state\server.json'
$version=if($cli){ & $cli.FullName --version }else{$null}
$hashes=@{};if(Test-Path $root){Get-ChildItem $root -File -Recurse | Where-Object {$_.Name -in @('launcher.cs','manager.py','env.sh','install.ps1','uninstall.ps1','login-sh','codex','pkill','awk')} | ForEach-Object {$hashes[$_.FullName.Substring($root.Length+1).Replace('\','/')]=(Get-FileHash $_.FullName).Hash}}
[PSCustomObject]@{installed=(Test-Path (Join-Path $root 'compat-shell.exe'));pythonAvailable=($null -ne $python);gitBashAvailable=(Test-Path "$env:ProgramFiles\Git\bin\bash.exe");codexVersion=$version;serverRecordPresent=(Test-Path $state);files=$hashes}|ConvertTo-Json -Depth 3 -Compress
'''
    result = subprocess.run(ssh_args + powershell(inventory), capture_output=True, timeout=30, check=True)
    status = json.loads(result.stdout.decode('utf-8-sig'))
    print('Remote inventory:', json.dumps(status, ensure_ascii=True))
    if args.check:
        return
    if not all(status.get(k) for k in ('pythonAvailable', 'gitBashAvailable', 'codexVersion')):
        raise RuntimeError('Remote Python, Git Bash, and Windows Codex are required')
    public = ensure_key(key)
    payload = archive_payload(public)
    script = r'''
$ErrorActionPreference='Stop';$ProgressPreference='SilentlyContinue'
[Console]::OutputEncoding=[Text.UTF8Encoding]::new($false)
$root=Join-Path $env:LOCALAPPDATA 'CodexSshCompat'
Add-Type -AssemblyName System.IO.Compression
Add-Type -AssemblyName System.IO.Compression.FileSystem
$memory=[IO.MemoryStream]::new([Convert]::FromBase64String([Console]::In.ReadToEnd().Trim()))
$zip=[IO.Compression.ZipArchive]::new($memory)
# Existing installation files must match. Never overwrite a live installation.
if(Test-Path (Join-Path $root 'compat-shell.exe')){
 foreach($entry in $zip.Entries){
  if($entry.FullName -in @('client.pub','install.ps1','uninstall.ps1')){continue}
  $dest=Join-Path $root $entry.FullName
  if(!(Test-Path $dest)){throw 'Existing adapter differs; preserve it and review an offline update first'}
  $s=$entry.Open();$reader=[IO.StreamReader]::new($s,[Text.Encoding]::UTF8,$true)
  try{$expected=$reader.ReadToEnd().Replace("`r`n","`n")}finally{$reader.Dispose()}
  if([IO.File]::ReadAllText($dest).Replace("`r`n","`n") -ne $expected){throw 'Existing adapter differs; preserve it and review an offline update first'}
 }
}
[IO.Directory]::CreateDirectory($root)|Out-Null
$sid=[Security.Principal.WindowsIdentity]::GetCurrent().User
$acl=[Security.AccessControl.DirectorySecurity]::new();$acl.SetOwner($sid)
$acl.SetAccessRuleProtection($true,$false)
$acl.AddAccessRule([Security.AccessControl.FileSystemAccessRule]::new($sid,'FullControl','ContainerInherit,ObjectInherit','None','Allow'))
[IO.Directory]::SetAccessControl($root,$acl)
foreach($entry in $zip.Entries){
 if($entry.FullName -eq 'client.pub'){
  $reader=[IO.StreamReader]::new($entry.Open());try{$publicKey=$reader.ReadToEnd()}finally{$reader.Dispose()}
  continue
 }
 $dest=[IO.Path]::GetFullPath((Join-Path $root $entry.FullName))
 if(!$dest.StartsWith($root+'\',[StringComparison]::OrdinalIgnoreCase)){throw 'Unsafe archive entry'}
 if(Test-Path $dest){
  if($entry.FullName -notin @('install.ps1','uninstall.ps1')){continue}
  $state=Join-Path $root 'state';[IO.Directory]::CreateDirectory($state)|Out-Null
  [IO.File]::Copy($dest,(Join-Path $state ($entry.Name+'.before-'+[DateTime]::UtcNow.ToString('yyyyMMddTHHmmssfff'))),$false)
 }
 [IO.Directory]::CreateDirectory([IO.Path]::GetDirectoryName($dest))|Out-Null
 $s=$entry.Open();try{$d=[IO.File]::Create($dest);try{$s.CopyTo($d)}finally{$d.Dispose()}}finally{$s.Dispose()}
}
$zip.Dispose();$memory.Dispose()
& ([scriptblock]::Create([IO.File]::ReadAllText((Join-Path $root 'install.ps1')))) -PublicKey $publicKey
'''
    result = subprocess.run(ssh_args + powershell(script), input=base64.b64encode(payload),
        capture_output=True, timeout=60)
    print(result.stdout.decode('utf-8', errors='replace'))
    if result.returncode:
        print(result.stderr.decode('utf-8', errors='replace'))
        raise SystemExit(result.returncode)
    if exists:
        print('Existing alias preserved:', args.alias)
        return
    if config.exists():
        backup = config.with_name('config.before-codex-compat-' + time.strftime('%Y%m%dT%H%M%S') + '-' + str(time.time_ns()))
        with backup.open('xb') as stream:
            stream.write(original_bytes)
        protect_file(backup)
    # Preserve the existing config's ACL; restrict only newly created files.
    # All installer-written text is BOM-free UTF-8; preserve existing bytes.
    if (config.read_bytes() if config.exists() else b'') != original_bytes:
        raise RuntimeError('SSH config changed during deployment; no local alias written')
    with config.open('wb') as stream:
        stream.write(block.encode('utf-8') + original_bytes)
    if not original_bytes:
        protect_file(config)
    effective(ssh, args.alias)  # OpenSSH must accept the generated config.
    print('Installed dedicated SSH alias:', args.alias)


if __name__ == '__main__':
    try:
        main()
    except (RuntimeError, OSError, ValueError, subprocess.SubprocessError) as error:
        # Avoid dumping subprocess arguments (encoded scripts / host details).
        print('Deployment failed: ' + (str(error) if not isinstance(error, subprocess.SubprocessError)
              else type(error).__name__ + '; inspect the connection locally'), file=sys.stderr)
        raise SystemExit(1)
