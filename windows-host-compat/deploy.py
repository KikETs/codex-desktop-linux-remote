#!/usr/bin/env python3
"""Install the Windows host adapter with a dedicated key and local SSH alias."""
import argparse
import base64
import io
from pathlib import Path
import re
import subprocess
import time
import zipfile

ROOT = Path(__file__).resolve().parent


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('destination', help='Existing working user@host or SSH alias')
    parser.add_argument('--alias', default='windows-codex-compat')
    parser.add_argument('--key', type=Path, default=Path.home() / '.ssh/codex_windows_compat_ed25519')
    args = parser.parse_args()
    if not re.fullmatch(r'[a-zA-Z0-9_-]+', args.alias):
        parser.error('Use an alias containing only letters, digits, underscores and hyphens')
    if args.destination.startswith('-') or any(c in args.destination for c in '\r\n\0'):
        parser.error('Invalid SSH destination')
    key = args.key.expanduser().resolve()
    if not key.exists():
        subprocess.run(['ssh-keygen', '-q', '-t', 'ed25519', '-N', '', '-C',
                        'codex-windows-ssh-compat', '-f', str(key)], check=True)
    public = Path(str(key) + '.pub').read_text()
    if not public.startswith('ssh-ed25519 ') or not public.strip().endswith(' codex-windows-ssh-compat'):
        parser.error('Use a dedicated key generated by this installer')
    payload = io.BytesIO()
    with zipfile.ZipFile(payload, 'w', zipfile.ZIP_DEFLATED) as archive:
        for name in ['install.ps1', 'uninstall.ps1', 'launcher.cs', 'manager.py', 'env.sh', 'bin/login-sh', 'bin/codex', 'bin/pkill', 'bin/awk']:
            archive.write(ROOT / name, name)
        archive.writestr('client.pub', public)
    script = r'''
$ErrorActionPreference='Stop';$ProgressPreference='SilentlyContinue'
$root=Join-Path $env:LOCALAPPDATA 'CodexSshCompat'
[IO.Directory]::CreateDirectory($root)|Out-Null
$sid=[Security.Principal.WindowsIdentity]::GetCurrent().User
$acl=[Security.AccessControl.DirectorySecurity]::new();$acl.SetOwner($sid)
$acl.SetAccessRuleProtection($true,$false)
$acl.AddAccessRule([Security.AccessControl.FileSystemAccessRule]::new($sid,'FullControl','ContainerInherit,ObjectInherit','None','Allow'))
[IO.Directory]::SetAccessControl($root,$acl)
Add-Type -AssemblyName System.IO.Compression
Add-Type -AssemblyName System.IO.Compression.FileSystem
$memory=[IO.MemoryStream]::new([Convert]::FromBase64String([Console]::In.ReadToEnd().Trim()))
$zip=[IO.Compression.ZipArchive]::new($memory)
foreach($entry in $zip.Entries){
 $dest=[IO.Path]::GetFullPath((Join-Path $root $entry.FullName))
 if(!$dest.StartsWith($root+'\',[StringComparison]::OrdinalIgnoreCase)){throw 'Unsafe archive entry'}
 [IO.Directory]::CreateDirectory([IO.Path]::GetDirectoryName($dest))|Out-Null
 $s=$entry.Open();try{$d=[IO.File]::Create($dest);try{$s.CopyTo($d)}finally{$d.Dispose()}}finally{$s.Dispose()}
}
$zip.Dispose();$memory.Dispose()
& ([scriptblock]::Create([IO.File]::ReadAllText((Join-Path $root 'install.ps1'))))
'''
    encoded = base64.b64encode(script.encode('utf-16le')).decode()
    result = subprocess.run(['ssh', '-T', '-o', 'BatchMode=yes', '-o', 'StrictHostKeyChecking=yes',
        '-o', 'ConnectTimeout=10', args.destination, 'powershell.exe', '-NoProfile', '-NonInteractive',
        '-EncodedCommand', encoded], input=base64.b64encode(payload.getvalue()),
        capture_output=True, timeout=60)
    print(result.stdout.decode('utf-8', errors='replace'))
    if result.returncode:
        print(result.stderr.decode('utf-8', errors='replace'))
        raise SystemExit(result.returncode)
    effective = subprocess.check_output(['ssh', '-G', args.destination], text=True)
    values = dict(line.split(' ', 1) for line in effective.splitlines() if ' ' in line)
    config = Path.home() / '.ssh/config'
    original = config.read_text() if config.exists() else ''
    if re.search(r'^Host\s+.*\b' + re.escape(args.alias) + r'\b', original, re.M):
        print('Existing alias preserved:', args.alias)
        return
    if config.exists():
        backup = config.with_name('config.before-codex-compat-' + time.strftime('%Y%m%dT%H%M%S'))
        backup.write_text(original); backup.chmod(0o600)
    block = (f'Host {args.alias}\n  HostName {values["hostname"]}\n  User {values["user"]}\n'
             f'  Port {values["port"]}\n  IdentityFile "{key}"\n  IdentitiesOnly yes\n'
             '  BatchMode yes\n  StrictHostKeyChecking yes\n\n')
    config.write_text(block + original); config.chmod(0o600)
    print('Installed dedicated SSH alias:', args.alias)


if __name__ == '__main__':
    main()
